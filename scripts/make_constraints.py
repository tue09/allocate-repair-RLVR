#!/usr/bin/env python3
"""Regenerate requirements/constraints-common.txt from verl's uv.lock.

The lock is exported with ``uv export --frozen --all-packages --extra vllm --extra fsdp`` (run inside
third_party/verl). CUDA-variant packages (torch, vLLM, flash-attn, NVIDIA runtime wheels, ...) and direct-URL
packages are dropped: scripts/setup_env.sh installs those explicitly for the detected CUDA variant. Everything else
keeps verl's tested pin.
"""

import argparse
import re

EXCLUDE = re.compile(
    r"^(cuda-|cupy|flash-attn|flash-linear-attention|flashinfer|humming-kernels|nvidia-(?!ml-py)|tilelang|"
    r"tokenspeed-triton|torch==|torchaudio|torchvision|torch-c-dlpack-ext|torchcodec|triton|vllm|xformers)"
)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("lock", help="uv export output (requirements format)")
    parser.add_argument("out")
    args = parser.parse_args()
    kept, dropped = [], []
    for line in open(args.lock):
        line = line.rstrip("\n")
        if not line or line.lstrip().startswith("#"):
            continue
        name = line.split(" ;")[0].strip()
        if " @ " in name or EXCLUDE.match(name):
            dropped.append(name)
            continue
        kept.append(line)
    with open(args.out, "w") as f:
        f.write("# Generated by scripts/make_constraints.py from verl v0.9.1 uv.lock (extras: vllm, fsdp).\n")
        f.write("# CUDA-variant and direct-URL packages are installed by scripts/setup_env.sh.\n")
        f.write("\n".join(kept) + "\n")
    print(f"kept {len(kept)} pins, dropped {len(dropped)}: {', '.join(sorted(dropped))}")


if __name__ == "__main__":
    main()
